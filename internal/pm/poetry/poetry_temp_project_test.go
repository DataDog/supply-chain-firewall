// Mirrors tests/package_managers/test_poetry_lock.py.

const pypiLockEntry = `# This file is automatically @generated by Poetry 2.0.0 and should not be changed by hand.

[[package]]
name = "requests"
version = "2.31.0"
description = "Python HTTP for Humans."
optional = false
python-versions = ">=3.7"
files = []
`

const privateSourceLockEntry = `# This file is automatically @generated by Poetry 2.0.0 and should not be changed by hand.

[[package]]
name = "internal-lib"
version = "1.0.0"
description = "An internal library."
optional = false
python-versions = ">=3.10"
files = []

[package.source]
type = "legacy"
url = "https://private.company.com/simple/"
reference = "private"
`

const localSourceLockEntry = `# This file is automatically @generated by Poetry 2.0.0 and should not be changed by hand.

[[package]]
name = "my-lib"
version = "0.1.0"
description = "A local library."
optional = false
python-versions = ">=3.10"
files = []

[package.source]
type = "directory"
url = "/absolute/path/to/my-lib"
`

const relativeLocalSourceLockEntry = `# This file is automatically @generated by Poetry 2.0.0 and should not be changed by hand.

[[package]]
name = "sibling-lib"
version = "0.1.0"
description = "A local library referenced by a relative path."
optional = false
python-versions = ">=3.10"
files = []

[package.source]
type = "directory"
url = "../sibling-lib"
`

func TestParsePoetryLockFile_PyPIPackage(t *testing.T) {
	lockPath := filepath.Join(t.TempDir(), "poetry.lock")
	if err := os.WriteFile(lockPath, []byte(pypiLockEntry), 0o644); err != nil {
		t.Fatalf("failed to write test lock file: %v", err)
	}

	sourceMap, err := parsePoetryLockFile(lockPath)
	if err != nil {
		t.Fatalf("parsePoetryLockFile() returned unexpected error: %v", err)
	}

	key := poetryPackageKey{name: "requests", version: "2.31.0"}
	want := "https://pypi.org/project/requests/2.31.0/"
	if got := sourceMap[key]; got != want {
		t.Fatalf("sourceMap[%+v] = %q, want %q", key, got, want)
	}
}

