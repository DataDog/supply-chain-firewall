func TestParsePoetryLockFile_RelativeLocalSource(t *testing.T) {
	projectDir := filepath.Join(t.TempDir(), "main-pkg")
	if err := os.MkdirAll(projectDir, 0o755); err != nil {
		t.Fatalf("failed to create project dir: %v", err)
	}
	lockPath := filepath.Join(projectDir, "poetry.lock")
	if err := os.WriteFile(lockPath, []byte(relativeLocalSourceLockEntry), 0o644); err != nil {
		t.Fatalf("failed to write test lock file: %v", err)
	}

	sourceMap, err := parsePoetryLockFile(lockPath)
	if err != nil {
		t.Fatalf("parsePoetryLockFile() returned unexpected error: %v", err)
	}

	key := poetryPackageKey{name: "sibling-lib", version: "0.1.0"}
	want, err := filepath.Abs(filepath.Join(projectDir, "..", "sibling-lib"))
	if err != nil {
		t.Fatalf("filepath.Abs() failed: %v", err)
	}
	if got := sourceMap[key]; got != want {
		t.Fatalf("sourceMap[%+v] = %q, want %q", key, got, want)
	}
}

