func TestResolvePoetryProjectDir_AllFlagForms(t *testing.T) {
	tests := []struct {
		name    string
		command []string
	}{
		{name: "space-separated long form", command: []string{"update", "--directory", "/tmp/proj"}},
		{name: "equals long form", command: []string{"update", "--directory=/tmp/proj"}},
		{name: "space-separated short form", command: []string{"update", "-C", "/tmp/proj"}},
		{name: "attached short form", command: []string{"update", "-C/tmp/proj"}},
		{name: "equals short form", command: []string{"update", "-C=/tmp/proj"}},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got, err := resolvePoetryProjectDir(tc.command)
			if err != nil {
				t.Fatalf("resolvePoetryProjectDir(%v) returned unexpected error: %v", tc.command, err)
			}
			if want := "/tmp/proj"; got != want {
				t.Fatalf("resolvePoetryProjectDir(%v) = %q, want %q", tc.command, got, want)
			}
		})
	}
}

func TestResolvePoetryProjectDir_NoFlagFallsBackToCwd(t *testing.T) {
	want, err := os.Getwd()
	if err != nil {
		t.Fatalf("os.Getwd() failed: %v", err)
	}

	got, err := resolvePoetryProjectDir([]string{"update"})
	if err != nil {
		t.Fatalf("resolvePoetryProjectDir() returned unexpected error: %v", err)
	}
	if got != want {
		t.Fatalf("resolvePoetryProjectDir() = %q, want %q", got, want)
	}
}

func TestStripPoetryDirectoryFlag_AllFlagForms(t *testing.T) {
	tests := []struct {
		name    string
		command []string
	}{
		{name: "space-separated long form", command: []string{"update", "--directory", "/tmp/proj", "--lock"}},
		{name: "equals long form", command: []string{"update", "--directory=/tmp/proj", "--lock"}},
		{name: "space-separated short form", command: []string{"update", "-C", "/tmp/proj", "--lock"}},
		{name: "attached short form", command: []string{"update", "-C/tmp/proj", "--lock"}},
		{name: "equals short form", command: []string{"update", "-C=/tmp/proj", "--lock"}},
	}

	want := []string{"update", "--lock"}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := stripPoetryDirectoryFlag(tc.command)
			if len(got) != len(want) {
				t.Fatalf("stripPoetryDirectoryFlag(%v) = %v, want %v", tc.command, got, want)
			}
			for i := range got {
				if got[i] != want[i] {
					t.Fatalf("stripPoetryDirectoryFlag(%v) = %v, want %v", tc.command, got, want)
				}
			}
		})
	}
}

func TestStripPoetryDirectoryFlag_NoFlagIsUnchanged(t *testing.T) {
	command := []string{"update", "--lock"}
	got := stripPoetryDirectoryFlag(command)
	if len(got) != len(command) {
		t.Fatalf("stripPoetryDirectoryFlag(%v) = %v, want unchanged %v", command, got, command)
	}
	for i := range got {
		if got[i] != command[i] {
			t.Fatalf("stripPoetryDirectoryFlag(%v) = %v, want unchanged %v", command, got, command)
		}
	}
}
